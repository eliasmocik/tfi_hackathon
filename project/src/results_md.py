    A(md(sfc, ".4f") + "\n")
    more = all(C(f"{c}_summary.csv", index_col=0).at["rule1N", "D_pct"] > C(f"{c}_summary.csv", index_col=0).at["rule1", "D_pct"] for c in CASES)
    lower = bool((sfc.SF_weighted_N < sfc.SF_weighted_P).all())
