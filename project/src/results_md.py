      f"(p = {f(r1.p_value, 3)}, N = {int(r1.N)}), " + ("significant at the 5 % level" if r1.p_value < 0.05 else "not significant at the 5 % level") + (" and negative" if r1.spearman_rho < 0 else " and positive") + ". Different fleets (2024 register vs 2026 units), different weather "
